# DATA TYPES: Different categories of data that Python can work with
# type() function: Returns the data type of a value/variable

# Basic Python Data Types:
pi = 3.14  # float: Decimal numbers with fractional part
_age = 23  # int: Whole numbers without decimal point
name = "Md Asif"  # str: Text/sequence of characters, enclosed in quotes
_bool = True  # bool: Boolean values - True or False (used for conditions)
_none = None  # NoneType: Special value representing absence of data

# Printing data types of each variable
print(type(_age))  # Output: <class 'int'>
print(type(pi))  # Output: <class 'float'>
print(type(name))  # Output: <class 'str'>
print(type(_bool))  # Output: <class 'bool'>
print(type(_none))  # Output: <class 'NoneType'>

