# VARIABLES: Named memory locations that store data values
# Naming conventions: Use snake_case for variables (words separated by underscores)
# Underscore prefix (_age) is a convention for internal-use variables (not enforced)

_age = 23  # Variable storing an integer value
name = "Md Asif"  # Variable storing a string value

# Variables can be used in print statements and mathematical operations
print("My Name is", name)  # Print string variable
print("Age", _age - 2)  # Print integer variable with arithmetic operation (_age - 2 = 21)