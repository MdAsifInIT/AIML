# BASIC OUTPUT AND STRING OPERATIONS
# print() function: Built-in function that outputs data to console
# String concatenation: Combining strings using + operator
# str() function: Converts other data types to string
# Note: Using + requires strings, while commas let print() convert values automatically
# Special characters: \n (newline), \t (tab) for formatting

print("Hello, World!" + " Welcome to Python programming." , " See you in " , str(3) + "!")
# Demonstrates: string concatenation (+), multiple arguments in print(), and type conversion

print("Below is lorem ipsum ... \n" + "Just Kidding!")
# Demonstrates: newline character (\n) to add line breaks

print("\t This is TAB!")
# Demonstrates: tab character (\t) for indentation/spacing